class ReceiptItem {
  final String id;

  final String receiptId;

  final String name;

  final double quantity;

  final String unit;

  final double price;

  final double total;


  ReceiptItem({

    required this.id,

    required this.receiptId,

    required this.name,

    required this.quantity,

    required this.unit,

    required this.price,

    required this.total,

  });

}